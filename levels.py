"""
levels.py —— 关卡数据。

每关用一个字典描述：
    name     关卡名（显示在界面上）
    rows     棋盘行数
    cols     棋盘列数
    mistakes 允许的失误次数
    arrows   箭头列表，每个元素是 (行, 列, 方向)，方向为 'U'/'D'/'L'/'R'

坐标约定：行号从 0 开始（0 在最上方），列号从 0 开始（0 在最左）。
所有关卡都已用 game.is_level_solvable 验证过“存在合理通关顺序”。

设计思路（供博客“关卡设计”部分参考）：
    每个关卡由若干条“链条”组成。一条链条里的箭头都朝同一方向、排成一行或一列，
    最靠近边界的那个箭头朝向棋盘外（一开始就能飞出），其余箭头朝向它。
    先飞出边界的那个，会为后面的箭头“让路”，于是后面的也能依次飞出。
    只要链条之间不互相堵死，关卡就一定可通关。
"""

